// Load on the mock server, then call runLocalizationChecks().
window.runLocalizationChecks=async()=>{
 const $=id=>document.getElementById(id),results=[];
 const assert=(value,label)=>{if(!value)throw Error(label);results.push(label);};
 const choose=async(language,scope)=>{document.querySelector(`${scope} [data-language="${language}"] span`).click();await new Promise(requestAnimationFrame);};
 const translatedContent=()=>{const content=document.body.cloneNode(true);content.querySelectorAll('.language-switch,script,style').forEach(element=>element.remove());return content.textContent;};
 await VelaI18n.ready;
 assert(document.documentElement.lang==='en','fresh browser defaults to English');
 assert($('login-button').getAttribute('aria-label')==='Connect','English login');
 assert(!/\p{Script=Han}/u.test(translatedContent()),'English UI has no untranslated Chinese');
 $('password').value='Connect';
 await choose('zh-Hans',$('desktop').hidden?'#landing-header':'.session-actions');
 assert(document.documentElement.lang==='zh-Hans','Chinese document language');
 assert($('login-button').getAttribute('aria-label')===VelaI18n.t('Connect'),'Chinese login');
 assert(/\p{Script=Han}/u.test($('password').placeholder),'Chinese password placeholder is visible');
 assert($('password').value==='Connect','language switch preserves password input without translating it');
 assert([...document.querySelectorAll('button[data-language]')].every(button=>button.getAttribute('aria-pressed')===String(button.dataset.language==='zh-Hans')),'both language switches stay synchronized');
 assert([...document.querySelectorAll('[data-language-name]')].every(name=>name.textContent===VelaI18n.t('Chinese')),'Chinese autonym remains visible');
 assert($('password-label').textContent===VelaI18n.t('Vela custom password'),'password label is translated');
 await choose('en',$('desktop').hidden?'#landing-header':'.session-actions');
 assert($('login-button').getAttribute('aria-label')==='Connect','return to English');
 $('password').value='fixture';$('login-form').requestSubmit();
 await new Promise(resolve=>setTimeout(resolve,800));
 assert(!$('desktop').hidden&&__peer.connectionState==='connected','fixture connects');
 const offers=__requests.filter(path=>path==='offer').length,peer=__peer;
 $('text').value='Connect';$('lock-text').value='unsent-fixture-only';
 $('stream-preference').value='text';$('stream-preference').dispatchEvent(new Event('change'));
 await choose('zh-Hans',$('desktop').hidden?'#landing-header':'.session-actions');
 assert($('control-state').textContent===VelaI18n.t('Control ready · Keyboard and mouse available'),'live state translated');
 assert($('text').value==='Connect','user-entered remote text is preserved');
 assert($('stream-preference').value==='text','streaming preference keeps its stable ID during language changes');
 assert($('lock-text').value==='unsent-fixture-only','language updates do not clear an unsent masked input');$('lock-text').value='';
 assert(__peer===peer&&__requests.filter(path=>path==='offer').length===offers,'language switch preserves peer and session');
 assert(localStorage.getItem('vela.language')==='zh-Hans','browser preference persists');
 await choose('en',$('desktop').hidden?'#landing-header':'.session-actions');
 assert(!/\p{Script=Han}/u.test(translatedContent()),'live session returns entirely to English');
 assert($('control-state').textContent==='Control ready · Keyboard and mouse available','live English state restored');
 return {passed:results.length,results};
};
